export async function purgeFakeJobsAndSeedReal() {
  try {
    logger.info('[PurgeSeed] Purging fake/Adzuna aggregator jobs from MongoDB...')
    
    // 1. Remove all adzuna jobs and non-tech junk jobs
    const deleteResult = await Internship.deleteMany({
      $or: [
        { source: 'adzuna' },
        { applyUrl: { $regex: /adzuna\./i } },
        { title: { $regex: /\b(plumber|care assistant|maintenance engineer|kitchen|cleaner|driver|cook|security guard|electrician|facilities technician|secretarial)\b/i } }
      ]
    })
    logger.info(`[PurgeSeed] Deleted ${deleteResult.deletedCount} fake/unrelated jobs`)

    // 2. Upsert verified real internships
    const now = Date.now()
    let seeded = 0

    for (const job of VERIFIED_REAL_INTERNSHIPS) {
      const postedAt = new Date(now - job.postedHoursAgo * 60 * 60 * 1000)
      const contentHash = crypto.createHash('sha256').update(`${job.companyName}|${job.title}|${job.externalId}`).digest('hex')
      
      await Internship.findOneAndUpdate(
        { externalId: job.externalId },
        {
          $set: {
            externalId: job.externalId,
            source: job.source,
            title: job.title,
            companyName: job.companyName,
            companyStage: job.companyStage,
            domain: job.domain,
            location: job.location,
            country: /india/i.test(job.location) ? 'IN' : 'US',
            city: job.location.split(/[,•/]/)[0]?.trim() || 'Remote',
            isRemote: job.isRemote,
            isHybrid: job.isHybrid,
            employmentType: job.employmentType,
            experienceLevel: job.experienceLevel,
            salaryText: job.salaryText,
            salaryCurrency: job.salaryCurrency,
            description: job.description,
            skills: job.skills,
            applyUrl: job.applyUrl,
            sourceUrl: job.linkedin_url || job.sourceUrl,
            contentHash: contentHash,
            metadata: {
              linkedin_url: job.linkedin_url
            },
            postedAt: postedAt,
            freshnessStatus: job.postedHoursAgo <= 48 ? 'fresh_48h' : 'standard',
            isInternship: true,
            isActive: true,
            lastSeenAt: new Date()
          }
        },
        { upsert: true, returnDocument: 'after' }
      )
      seeded++
    }

    logger.info(`[PurgeSeed] Successfully seeded ${seeded} 100% verified real internships with exact direct links!`)
    return { deleted: deleteResult.deletedCount, seeded }
  } catch (err) {
    logger.error(`[PurgeSeed] Error during purge & seed: ${err.message}`)
    throw err
  }
}
